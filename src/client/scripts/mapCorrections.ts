export default function initMapCorrections(client: Client) {
    let lastExitsRoomId: number | undefined = undefined;

    client.on("gmcp_msg.room.exits", () => {
        lastExitsRoomId = client.Map.currentRoom?.id;
    });

    client.Triggers.registerTrigger(
        /^[ >]*Nie widzisz zadnego wyjscia prowadzacego na (.+)\.$/,
        (line, matches) => {
            const room = client.Map.currentRoom;
            if (!room) return line;

            const area = room.area;
            const isAllowedArea =
                area === 52 ||
                area === 50 ||
                area === 40 ||
                (area === 35 && STIRLAND.has(room.id)) ||
                (area === 44 && VARIENO.has(room.id));
            if (!isAllowedArea) {
                return line;
            }

            // Skip correction for specific room range
            if (room.id >= 20812 && room.id < 20903) {
                return line;
            }

            // Only correct for standard directions
            if (STANDARD_DIRECTIONS.indexOf(matches[1]) === -1) {
                return line;
            }

            // Avoid correcting if we haven't moved
            if (lastExitsRoomId === room.id) {
                return line;
            }

            client.Map.moveBack();
            return line;
        },
        "map-corrections",
    );
}
